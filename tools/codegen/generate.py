#!/usr/bin/env python3
"""obs_schema.yaml -> C++ header + Python module. `--check` fails if the committed files are stale."""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
HPP = ROOT / "perception/include/perception/obs_layout.hpp"
PY = ROOT / "policy/swarm_policy/obs_layout.py"
HEADER = "Generated by tools/codegen/generate.py from scenarios/schema/obs_schema.yaml. Do not edit."


def render() -> tuple[str, str]:
    s = yaml.safe_load((ROOT / "scenarios/schema/obs_schema.yaml").read_text())
    n = s["normalisation"]
    cpp = [f"// {HEADER}", "#pragma once", "", "namespace perception::obs {",
           f"inline constexpr int kSchemaVersion = {s['schema_version']};",
           f"inline constexpr double kPosNorm = {n['pos']};",
           f"inline constexpr double kTimeNorm = {n['time']};"]
    py = [f'"""{HEADER}"""', "", f"SCHEMA_VERSION = {s['schema_version']}", f"POS_NORM = {n['pos']}",
          f"TIME_NORM = {n['time']}", "", "LAYOUT: dict[str, dict[str, tuple[int, int, str]]] = {"]
    dims = {}
    for kind, fields in s["kinds"].items():
        cpp.append(f"namespace {kind}_ {{")
        py.append(f'    "{kind}": {{')
        off = 0
        for f in fields:
            cpp.append(f"inline constexpr int {f['name']} = {off};")
            py.append(f'        "{f["name"]}": ({off}, {off + f["dim"]}, "{f["norm"]}"),')
            off += f["dim"]
        cpp += [f"inline constexpr int kDim = {off};", f"}}  // namespace {kind}_"]
        py.append("    },")
        dims[kind] = off
    cpp += ["}  // namespace perception::obs", ""]
    py += ["}", "", f"DIMS: dict[str, int] = {dims}", ""]
    return "\n".join(cpp), "\n".join(py)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    check = ap.parse_args().check
    hpp, py = render()
    if check:
        if HPP.read_text() != hpp or PY.read_text() != py:
            sys.exit("Generated observation layout is stale: run tools/codegen/generate.py")
        print("codegen up to date")
        return
    HPP.parent.mkdir(parents=True, exist_ok=True)
    HPP.write_text(hpp)
    PY.write_text(py)


if __name__ == "__main__":
    main()
